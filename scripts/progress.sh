#!/usr/bin/env bash
#
# OpenForge progress report.
#
# Prints a progress bar per parity area plus an overall estimate, and can write
# the same report to PROGRESS.md.
#
#   scripts/progress.sh            # print
#   scripts/progress.sh --write    # print and update PROGRESS.md
#
# Two kinds of number are reported and they are deliberately kept apart:
#
#   * MEASURED  — crates, test functions and lines of Rust are counted from the
#                 repository on every run; they cannot drift from reality.
#   * CURATED   — the per-area percentage is a human judgement (see AREAS
#                 below). "Parity with ZModeler" has no machine-checkable
#                 definition, so these are estimates. Edit them as work lands.
#
# The overall figure is the unweighted mean of the areas, which is the
# weakest part of this report: areas are not equally sized. Treat it as a
# rough indicator, not a measurement.

set -euo pipefail
cd "$(dirname "$0")/.."

WRITE=0
[ "${1:-}" = "--write" ] && WRITE=1

# --- measured ----------------------------------------------------------------

crates=$(find crates -maxdepth 1 -mindepth 1 -type d | wc -l | tr -d ' ')
test_fns=$(grep -rh '#\[test\]' crates 2>/dev/null | wc -l | tr -d ' ')
rust_loc=$(find crates -name '*.rs' -print0 | xargs -0 cat | wc -l | tr -d ' ')

# --- curated: area | score | group ------------------------------------------
#
# Keep the scores honest rather than flattering: a score is "how much of a
# shipped, usable feature is here", so 100 means indistinguishable from the
# reference app, and 0 means not started.

AREAS=$(cat <<'DATA'
Data model (nodes, mesh, selection, undo, tools)|85|Engine
Standard format IO (OBJ, glTF/GLB, PLY, STL)|65|Engine
Modeling ops (extrude, inset, bevel, mirror, weld, deformers)|80|Engine
Boolean CSG|65|Engine
Generators & algorithms (primitives, Catmull-Clark, noise, L-systems)|80|Engine
Materials & textures|72|Engine
Animation (tracks, clips, playback)|55|Engine
Rigging & skinning|60|Engine
UV math (project, unwrap, pack, edits)|85|Engine
GPU viewport (depth, shading, grid, gizmo)|88|UI
Viewport editing UX (gizmos, wireframe, outlines, picking)|93|UI
UV editor UI|58|UI
Panels & dialogs (outliner, properties, toolbars)|52|UI
Import/export UX|40|UI
Plugin / service host|35|UI
Game tooling (LOD, dummies/TXD, vehicles)|5|UI
DATA
)

bar() {
    local pct=$1 filled i out=""
    filled=$((pct / 5))
    for ((i = 0; i < 20; i++)); do
        if [ "$i" -lt "$filled" ]; then out="${out}█"; else out="${out}░"; fi
    done
    printf '%s %3d%%' "$out" "$pct"
}

report() {
    echo "OpenForge — progress toward ZModeler parity"
    echo
    local total=0 count=0 group="" first=1
    while IFS='|' read -r name pct grp; do
        [ -z "$name" ] && continue
        if [ "$grp" != "$group" ]; then
            [ "$first" -eq 0 ] && echo
            first=0
            group="$grp"
            if [ "$grp" = "Engine" ]; then echo "ENGINE"; else echo "APPLICATION SURFACE"; fi
        fi
        printf '  %-52s %s\n' "$name" "$(bar "$pct")"
        total=$((total + pct))
        count=$((count + 1))
    done <<<"$AREAS"
    echo
    local overall=$((total / count))
    printf '  %-52s %s\n' "OVERALL (unweighted mean of $count areas)" "$(bar "$overall")"
    echo
    printf 'Measured from the repo: %s crates · %s test fns · %s lines of Rust\n' \
        "$crates" "$test_fns" "$rust_loc"
    # The OVERALL bar can only show whole percent; the exact mean is repeated
    # here with a decimal so that a single area moving is still visible.
    printf 'Exact mean of the curated area scores: %s.%s%% (sum %s over %s areas)\n' \
        "$((total * 10 / count / 10))" "$((total * 10 / count % 10))" "$total" "$count"
    echo "The per-area scores are curated estimates; only the counts above are measured."
}

if [ "$WRITE" -eq 1 ]; then
    {
        echo "# OpenForge — progress"
        echo
        echo "<!-- Generated by scripts/progress.sh --write. Do not hand-edit. -->"
        echo
        echo '```'
        report
        echo '```'
        echo
        echo "Regenerate with \`scripts/progress.sh --write\`; see"
        echo "[\`HANDOFF.md\`](HANDOFF.md) §7 for the narrative version."
    } >PROGRESS.md
    echo "wrote PROGRESS.md"
    echo
fi

report
